//! Generates `src/width_table_data.rs` from the Unicode Character Database.
//!
//! `cargo run -p text_layout --example gen_width_table -- <ucd dir> <output file>`
//!
//! `<ucd dir>` holds `EastAsianWidth.txt`, `extracted/DerivedGeneralCategory.txt`
//! and `emoji/emoji-data.txt`, all from the same Unicode version.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const CODE_POINTS: usize = 0x11_0000;
const BLOCK_CPS: usize = 256;
const BLOCK_BYTES: usize = BLOCK_CPS / 4;

/// One UCD data file: `range ; value # comment` lines.
struct UcdFile {
    text: String,
}

impl UcdFile {
    fn read(path: &Path) -> Self {
        let text = std::fs::read_to_string(path)
            .unwrap_or_else(|e| panic!("reading {}: {e}", path.display()));
        Self { text }
    }

    /// Every `(first, last, value)` entry, ranges inclusive.
    fn entries(&self) -> impl Iterator<Item = (usize, usize, &str)> {
        self.text.lines().filter_map(|line| {
            let data = line.split('#').next()?.trim();
            let (range, value) = data.split_once(';')?;
            let (first, last) = match range.trim().split_once("..") {
                Some((a, b)) => (a, b),
                None => (range.trim(), range.trim()),
            };
            let first = usize::from_str_radix(first, 16).ok()?;
            let last = usize::from_str_radix(last, 16).ok()?;
            Some((first, last, value.trim()))
        })
    }
}

/// The cell width of every code point, 0, 1 or 2.
struct WidthMap {
    widths: Vec<u8>,
}

impl WidthMap {
    /// Wide: East Asian Width W or F, or `Emoji_Presentation`. Zero: General
    /// Category Mn, Me, Cf or Cc, and the Hangul medial vowels and final
    /// consonants that join a leading consonant. Zero wins over wide.
    fn from_ucd(dir: &Path) -> Self {
        let mut widths = vec![1u8; CODE_POINTS];
        let eaw = UcdFile::read(&dir.join("EastAsianWidth.txt"));
        Self::set(&mut widths, &eaw, 2, |v| matches!(v, "W" | "F"));
        let emoji = UcdFile::read(&dir.join("emoji/emoji-data.txt"));
        Self::set(&mut widths, &emoji, 2, |v| v == "Emoji_Presentation");
        let gc = UcdFile::read(&dir.join("extracted/DerivedGeneralCategory.txt"));
        Self::set(&mut widths, &gc, 0, |v| matches!(v, "Mn" | "Me" | "Cf" | "Cc"));
        widths[0x1160..=0x11ff].fill(0);
        widths[0xd7b0..=0xd7ff].fill(0);
        Self { widths }
    }

    fn set(widths: &mut [u8], file: &UcdFile, width: u8, wanted: impl Fn(&str) -> bool) {
        for (first, last, value) in file.entries() {
            if wanted(value) {
                widths[first..=last].fill(width);
            }
        }
    }

    /// Two bits per code point, four per byte, low bits first.
    fn packed_block(&self, block: usize) -> [u8; BLOCK_BYTES] {
        let mut out = [0u8; BLOCK_BYTES];
        let base = block * BLOCK_CPS;
        for (i, &w) in self.widths[base..base + BLOCK_CPS].iter().enumerate() {
            out[i / 4] |= w << ((i % 4) * 2);
        }
        out
    }
}

/// The two-level table: a block index per 256 code points, and the
/// deduplicated blocks it points into.
struct WidthTable {
    index: Vec<u8>,
    blocks: Vec<[u8; BLOCK_BYTES]>,
}

impl WidthTable {
    fn build(map: &WidthMap) -> Self {
        let mut seen = HashMap::new();
        let mut blocks = Vec::new();
        let index = (0..CODE_POINTS / BLOCK_CPS)
            .map(|b| {
                let packed = map.packed_block(b);
                *seen.entry(packed).or_insert_with(|| {
                    blocks.push(packed);
                    u8::try_from(blocks.len() - 1).expect("more than 256 distinct blocks")
                })
            })
            .collect();
        Self { index, blocks }
    }

    fn render(&self, version: &str) -> String {
        let mut s = String::new();
        let _ = writeln!(
            s,
            "//! Generated by `cargo run -p text_layout --example gen_width_table` from\n\
             //! Unicode {version}. Do not edit by hand.\n\n\
             use crate::width_table::WidthTable;\n\n\
             impl WidthTable {{\n    \
             #[rustfmt::skip]\n    \
             pub const INDEX: [u8; {}] = [",
            self.index.len()
        );
        for row in self.index.chunks(16) {
            let _ = writeln!(s, "        {}", Self::bytes(row));
        }
        let _ = writeln!(
            s,
            "    ];\n\n    #[rustfmt::skip]\n    pub const BLOCKS: [[u8; {BLOCK_BYTES}]; {}] = [",
            self.blocks.len()
        );
        for block in &self.blocks {
            s.push_str("        [\n");
            for row in block.chunks(16) {
                let _ = writeln!(s, "            {}", Self::bytes(row));
            }
            s.push_str("        ],\n");
        }
        s.push_str("    ];\n}\n");
        s
    }

    fn bytes(row: &[u8]) -> String {
        row.iter().map(|b| format!("0x{b:02x},")).collect::<Vec<_>>().join(" ")
    }
}

/// The command line: UCD directory and output path.
struct Generator {
    ucd: PathBuf,
    out: PathBuf,
}

impl Generator {
    fn from_args() -> Self {
        let mut args = std::env::args_os().skip(1);
        let usage = "usage: gen_width_table <ucd dir> <output file>";
        let ucd = PathBuf::from(args.next().expect(usage));
        let out = PathBuf::from(args.next().expect(usage));
        Self { ucd, out }
    }

    /// The version from the first line of `EastAsianWidth.txt`,
    /// `# EastAsianWidth-16.0.0.txt`.
    fn version(&self) -> String {
        let head = UcdFile::read(&self.ucd.join("EastAsianWidth.txt")).text;
        let first = head.lines().next().unwrap_or_default();
        first
            .trim_start_matches("# EastAsianWidth-")
            .trim_end_matches(".txt")
            .to_owned()
    }

    fn run(&self) {
        let table = WidthTable::build(&WidthMap::from_ucd(&self.ucd));
        std::fs::write(&self.out, table.render(&self.version()))
            .unwrap_or_else(|e| panic!("writing {}: {e}", self.out.display()));
        eprintln!("{} distinct blocks", table.blocks.len());
    }
}

fn main() {
    Generator::from_args().run();
}
